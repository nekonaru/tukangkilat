-- V16: offline sync, simulated chat keys, rate limits, API versions and widgets.
CREATE TABLE IF NOT EXISTS sync_operations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    entity      VARCHAR(64) NOT NULL,
    entity_id   VARCHAR(64) NOT NULL DEFAULT '',
    operation   VARCHAR(16) NOT NULL,
    payload     TEXT NOT NULL DEFAULT '',
    version     INT NOT NULL DEFAULT 1,
    status      VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    conflict    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    synced_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_sync_user ON sync_operations (user_id, status);

CREATE TABLE IF NOT EXISTS chat_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    public_key  VARCHAR(512) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_chat_key UNIQUE (user_id, fingerprint)
);

CREATE TABLE IF NOT EXISTS rate_limits (
    code        VARCHAR(64) PRIMARY KEY,
    max_calls   INT NOT NULL DEFAULT 60,
    window_sec  INT NOT NULL DEFAULT 60,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS api_versions (
    version     VARCHAR(16) PRIMARY KEY,
    status      VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    note        VARCHAR(255) NOT NULL DEFAULT '',
    released_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS widget_configs (
    user_id     BIGINT NOT NULL REFERENCES users (id),
    widget_type VARCHAR(48) NOT NULL,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    position    INT NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, widget_type)
);

CREATE TABLE IF NOT EXISTS scheduled_jobs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    interval_ms BIGINT NOT NULL DEFAULT 60000,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    last_run    TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
