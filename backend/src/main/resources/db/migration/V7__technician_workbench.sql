-- Technician availability, portfolio and payout account.
CREATE TABLE IF NOT EXISTS availability_blocks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    block_date   DATE NOT NULL,
    slot_label   VARCHAR(32) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_tech_block UNIQUE (technician_id, block_date, slot_label)
);
CREATE TABLE IF NOT EXISTS technician_portfolios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    photo_url     VARCHAR(512) NOT NULL,
    caption       VARCHAR(255) NOT NULL DEFAULT '',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS payout_accounts (
    technician_id BIGINT PRIMARY KEY REFERENCES users (id),
    bank          VARCHAR(64) NOT NULL,
    account_no    VARCHAR(64) NOT NULL,
    account_name  VARCHAR(120) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
