-- Consumer wallet, loyalty points and recurring service subscriptions.
CREATE TABLE IF NOT EXISTS wallets (
    user_id    BIGINT PRIMARY KEY REFERENCES users (id),
    balance    BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS wallet_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    amount     BIGINT NOT NULL,
    type       VARCHAR(16) NOT NULL,
    reference  VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_wallet_tx_user ON wallet_transactions (user_id, created_at);
CREATE TABLE IF NOT EXISTS loyalty_points (
    user_id   BIGINT PRIMARY KEY REFERENCES users (id),
    points    INT NOT NULL DEFAULT 0 CHECK (points >= 0),
    lifetime  INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS subscriptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id  BIGINT NOT NULL REFERENCES users (id),
    service_id   BIGINT NOT NULL REFERENCES services (id),
    address_id   BIGINT NOT NULL REFERENCES addresses (id),
    interval_days INT NOT NULL DEFAULT 30 CHECK (interval_days > 0),
    next_date    DATE NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_subscriptions_due ON subscriptions (status, next_date);
