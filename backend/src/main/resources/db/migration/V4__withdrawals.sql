-- Simulated balance withdrawals by technicians (PRD T-11).
CREATE TABLE IF NOT EXISTS withdrawals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    amount       BIGINT NOT NULL CHECK (amount > 0),
    status       VARCHAR(24) NOT NULL DEFAULT 'SELESAI',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_withdrawals_tech ON withdrawals (technician_id, created_at);
