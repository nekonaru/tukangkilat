-- V12: platform analytics, configuration, moderation and scheduled content.
CREATE TABLE IF NOT EXISTS feature_flags (
    flag_key    VARCHAR(64) PRIMARY KEY,
    enabled     BOOLEAN NOT NULL DEFAULT FALSE,
    target_role VARCHAR(16) NOT NULL DEFAULT '',
    note        VARCHAR(255) NOT NULL DEFAULT '',
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS content_pages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64) NOT NULL UNIQUE,
    title      VARCHAR(120) NOT NULL,
    body       TEXT NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS scheduled_broadcasts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    body        TEXT NOT NULL,
    target_role VARCHAR(16) NOT NULL DEFAULT '',
    send_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_by  BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS review_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_order_id BIGINT NOT NULL REFERENCES ratings (order_id),
    reporter_id BIGINT NOT NULL REFERENCES users (id),
    reason      VARCHAR(255) NOT NULL DEFAULT '',
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    resolved_by BIGINT REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_review_report UNIQUE (review_order_id, reporter_id)
);

CREATE TABLE IF NOT EXISTS sla_policies (
    code        VARCHAR(32) PRIMARY KEY,
    minutes     INT NOT NULL,
    compensation BIGINT NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS sla_breaches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id),
    policy_code VARCHAR(32) NOT NULL REFERENCES sla_policies (code),
    minutes_late INT NOT NULL DEFAULT 0,
    compensated BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_sla_breach UNIQUE (order_id, policy_code)
);

CREATE TABLE IF NOT EXISTS admin_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT NOT NULL REFERENCES users (id),
    target_type VARCHAR(32) NOT NULL,
    target_id  BIGINT NOT NULL,
    note       TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weekly_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_start  DATE NOT NULL UNIQUE,
    orders      INT NOT NULL DEFAULT 0,
    revenue     BIGINT NOT NULL DEFAULT 0,
    new_users   INT NOT NULL DEFAULT 0,
    disputes    INT NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
