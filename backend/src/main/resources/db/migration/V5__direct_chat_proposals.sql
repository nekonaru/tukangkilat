-- Direct negotiation between a consumer and a technician, plus price proposals.
CREATE TABLE IF NOT EXISTS direct_messages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id   BIGINT NOT NULL REFERENCES users (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    sender_id     BIGINT NOT NULL REFERENCES users (id),
    body          TEXT NOT NULL CHECK (char_length(body) <= 2000),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_direct_messages_pair ON direct_messages (consumer_id, technician_id, created_at);

CREATE TABLE IF NOT EXISTS proposals (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id   BIGINT NOT NULL REFERENCES users (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    service_id    BIGINT NOT NULL REFERENCES services (id),
    description   TEXT NOT NULL,
    price         BIGINT NOT NULL CHECK (price > 0),
    scheduled_date DATE NOT NULL,
    custom_time   VARCHAR(32),
    status        VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_proposals_consumer ON proposals (consumer_id, status, created_at);
