-- V15: technician reputation, academy, teams, field permits and economy.
CREATE TABLE IF NOT EXISTS reputation_scores (
    technician_id BIGINT PRIMARY KEY REFERENCES users (id),
    quality       INT NOT NULL DEFAULT 0,
    response      INT NOT NULL DEFAULT 0,
    punctuality   INT NOT NULL DEFAULT 0,
    satisfaction  INT NOT NULL DEFAULT 0,
    overall       INT NOT NULL DEFAULT 0,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS certifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    code          VARCHAR(48) NOT NULL,
    title         VARCHAR(120) NOT NULL,
    expires_at    DATE NOT NULL,
    status        VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    score         INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_certification UNIQUE (technician_id, code)
);

CREATE TABLE IF NOT EXISTS courses (
    code        VARCHAR(48) PRIMARY KEY,
    title       VARCHAR(120) NOT NULL,
    minutes     INT NOT NULL DEFAULT 30,
    reward_points INT NOT NULL DEFAULT 50
);

CREATE TABLE IF NOT EXISTS enrollments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    course_code   VARCHAR(48) NOT NULL REFERENCES courses (code),
    progress      INT NOT NULL DEFAULT 0,
    completed     BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_enrollment UNIQUE (technician_id, course_code)
);

CREATE TABLE IF NOT EXISTS gear_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    name          VARCHAR(120) NOT NULL,
    price_points  INT NOT NULL DEFAULT 100,
    owned         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_gear UNIQUE (technician_id, name)
);

CREATE TABLE IF NOT EXISTS teams (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id     BIGINT NOT NULL REFERENCES users (id),
    name        VARCHAR(120) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS team_helpers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     BIGINT NOT NULL REFERENCES teams (id),
    helper_id   BIGINT NOT NULL REFERENCES users (id),
    status      VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_helper UNIQUE (team_id, helper_id)
);

CREATE TABLE IF NOT EXISTS availability_heatmap (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    day_of_week   INT NOT NULL,
    hour_slot     INT NOT NULL,
    weight        INT NOT NULL DEFAULT 1,
    CONSTRAINT uq_heatmap UNIQUE (technician_id, day_of_week, hour_slot)
);

CREATE TABLE IF NOT EXISTS work_permits (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    permit_code VARCHAR(32) NOT NULL UNIQUE,
    issued_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    closed_at   TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS earnings_forecasts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    period        VARCHAR(16) NOT NULL,
    expected      BIGINT NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tax_simulations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    gross         BIGINT NOT NULL,
    tax_percent   INT NOT NULL,
    tax_amount    BIGINT NOT NULL,
    net           BIGINT NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS payout_schedules (
    technician_id BIGINT PRIMARY KEY REFERENCES users (id),
    frequency     VARCHAR(16) NOT NULL DEFAULT 'MINGGUAN',
    min_amount    BIGINT NOT NULL DEFAULT 100000,
    enabled       BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS quality_scores (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    score         INT NOT NULL DEFAULT 0,
    note          VARCHAR(255) NOT NULL DEFAULT '',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_quality UNIQUE (order_id)
);

CREATE TABLE IF NOT EXISTS storefronts (
    technician_id BIGINT PRIMARY KEY REFERENCES users (id),
    headline      VARCHAR(120) NOT NULL DEFAULT '',
    description   TEXT NOT NULL DEFAULT '',
    custom_price  BIGINT NOT NULL DEFAULT 0,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
