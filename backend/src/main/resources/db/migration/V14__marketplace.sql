-- V14: dynamic marketplace, gifting, wishlist and admin commerce operations.
CREATE TABLE IF NOT EXISTS custom_bundles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    name        VARCHAR(120) NOT NULL,
    service_ids VARCHAR(255) NOT NULL,
    total_price BIGINT NOT NULL DEFAULT 0,
    discount    BIGINT NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS flash_sales (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services (id),
    discount_percent INT NOT NULL DEFAULT 0,
    quota      INT NOT NULL DEFAULT 0,
    used       INT NOT NULL DEFAULT 0,
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS group_buys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    service_id  BIGINT NOT NULL REFERENCES services (id),
    area_name   VARCHAR(120) NOT NULL,
    target_count INT NOT NULL DEFAULT 5,
    joined_count INT NOT NULL DEFAULT 1,
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS job_bids (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    price         BIGINT NOT NULL,
    note          VARCHAR(255) NOT NULL DEFAULT '',
    status        VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_job_bid UNIQUE (order_id, technician_id)
);

CREATE TABLE IF NOT EXISTS gift_cards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL UNIQUE,
    sender_id   BIGINT NOT NULL REFERENCES users (id),
    receiver_id BIGINT REFERENCES users (id),
    amount      BIGINT NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS point_shop_items (
    code        VARCHAR(48) PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    points      INT NOT NULL,
    description VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS point_redemptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    item_code   VARCHAR(48) NOT NULL REFERENCES point_shop_items (code),
    points      INT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tips (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id),
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    amount      BIGINT NOT NULL,
    note        VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_tip UNIQUE (order_id)
);

CREATE TABLE IF NOT EXISTS wishlists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    service_id  BIGINT NOT NULL REFERENCES services (id),
    target_price BIGINT NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_wishlist UNIQUE (consumer_id, service_id)
);

CREATE TABLE IF NOT EXISTS price_alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    service_id  BIGINT NOT NULL REFERENCES services (id),
    target_price BIGINT NOT NULL,
    triggered   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS price_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services (id),
    price      BIGINT NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ledger_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL UNIQUE,
    account     VARCHAR(64) NOT NULL,
    debit       BIGINT NOT NULL DEFAULT 0,
    credit      BIGINT NOT NULL DEFAULT 0,
    reference   VARCHAR(128) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS commission_rules (
    code        VARCHAR(48) PRIMARY KEY,
    service_id  BIGINT REFERENCES services (id),
    percent     INT NOT NULL DEFAULT 15,
    priority    INT NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
