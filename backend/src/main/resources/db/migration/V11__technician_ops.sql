-- V11: technician documents, service areas, auto accept, field operations and performance.
CREATE TABLE IF NOT EXISTS tech_documents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    doc_type    VARCHAR(32) NOT NULL,
    file_url    VARCHAR(512) NOT NULL,
    expires_at  DATE,
    status      VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    note        VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_tech_doc UNIQUE (technician_id, doc_type)
);
CREATE INDEX IF NOT EXISTS idx_tech_doc_tech ON tech_documents (technician_id, status);

CREATE TABLE IF NOT EXISTS service_areas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    area_name     VARCHAR(120) NOT NULL,
    lat           DOUBLE PRECISION NOT NULL,
    lng           DOUBLE PRECISION NOT NULL,
    radius_km     INT NOT NULL DEFAULT 10,
    is_excluded   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auto_accept_rules (
    technician_id BIGINT PRIMARY KEY REFERENCES users (id),
    enabled       BOOLEAN NOT NULL DEFAULT FALSE,
    min_price     BIGINT NOT NULL DEFAULT 0,
    max_distance  INT NOT NULL DEFAULT 20,
    service_ids   VARCHAR(255) NOT NULL DEFAULT '',
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS checkins (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    kind       VARCHAR(16) NOT NULL,
    lat        DOUBLE PRECISION NOT NULL,
    lng        DOUBLE PRECISION NOT NULL,
    distance_m INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_checkin UNIQUE (order_id, kind)
);

CREATE TABLE IF NOT EXISTS job_materials (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    technician_id BIGINT NOT NULL REFERENCES users (id),
    name       VARCHAR(120) NOT NULL,
    quantity   INT NOT NULL DEFAULT 1,
    cost       BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tech_badges (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    code       VARCHAR(48) NOT NULL,
    title      VARCHAR(120) NOT NULL,
    earned_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_tech_badge UNIQUE (technician_id, code)
);

CREATE TABLE IF NOT EXISTS chat_templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    title      VARCHAR(80) NOT NULL,
    body       VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS leave_requests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    start_date DATE NOT NULL,
    end_date   DATE NOT NULL,
    reason     VARCHAR(255) NOT NULL DEFAULT '',
    status     VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS work_journals (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    entry_date DATE NOT NULL,
    note       TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS equipment_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    name       VARCHAR(120) NOT NULL,
    checked    BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_equipment UNIQUE (technician_id, name)
);
