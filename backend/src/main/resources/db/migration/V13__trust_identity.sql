-- V13: trust, identity, privacy and admin trust operations.
CREATE TABLE IF NOT EXISTS trusted_devices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    device_name VARCHAR(120) NOT NULL,
    device_id   VARCHAR(120) NOT NULL,
    trusted     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    last_seen   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_trusted_device UNIQUE (user_id, device_id)
);

CREATE TABLE IF NOT EXISTS user_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    device_name VARCHAR(120) NOT NULL,
    ip_address  VARCHAR(64) NOT NULL DEFAULT '',
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    last_active TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    revoked     BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON user_sessions (user_id, revoked);

CREATE TABLE IF NOT EXISTS consents (
    user_id     BIGINT NOT NULL REFERENCES users (id),
    kind        VARCHAR(32) NOT NULL,
    granted     BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, kind)
);

CREATE TABLE IF NOT EXISTS user_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    blocked_id  BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_block UNIQUE (user_id, blocked_id)
);

CREATE TABLE IF NOT EXISTS sos_alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    order_id    BIGINT REFERENCES orders (id),
    lat         DOUBLE PRECISION NOT NULL DEFAULT 0,
    lng         DOUBLE PRECISION NOT NULL DEFAULT 0,
    note        VARCHAR(255) NOT NULL DEFAULT '',
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS app_locks (
    user_id      BIGINT PRIMARY KEY REFERENCES users (id),
    pin_hash     VARCHAR(128) NOT NULL,
    enabled      BOOLEAN NOT NULL DEFAULT FALSE,
    failed_count INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS two_factors (
    user_id      BIGINT PRIMARY KEY REFERENCES users (id),
    enabled      BOOLEAN NOT NULL DEFAULT FALSE,
    otp_code     VARCHAR(16) NOT NULL DEFAULT '',
    otp_expires  TIMESTAMP WITH TIME ZONE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS login_alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    device_name VARCHAR(120) NOT NULL,
    ip_address  VARCHAR(64) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    is_read     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS subadmin_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT NOT NULL REFERENCES users (id),
    role_name   VARCHAR(48) NOT NULL,
    permissions VARCHAR(512) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_subadmin_role UNIQUE (admin_id, role_name)
);

CREATE TABLE IF NOT EXISTS incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL UNIQUE,
    title       VARCHAR(120) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    severity    VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    runbook     TEXT NOT NULL DEFAULT '',
    created_by  BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS retention_policies (
    code        VARCHAR(48) PRIMARY KEY,
    policy_table VARCHAR(64) NOT NULL,
    days        INT NOT NULL DEFAULT 90,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS backup_jobs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    frequency   VARCHAR(16) NOT NULL DEFAULT 'HARIAN',
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    last_run    TIMESTAMP WITH TIME ZONE,
    next_run    TIMESTAMP WITH TIME ZONE,
    created_by  BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
