-- V10: service catalog, bundles, vouchers, referral, installment, loyalty tiers and order extras.
CREATE TABLE IF NOT EXISTS service_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL UNIQUE,
    icon       VARCHAR(64) NOT NULL DEFAULT '',
    sort_order INT NOT NULL DEFAULT 0,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE services ADD COLUMN IF NOT EXISTS category_id BIGINT REFERENCES service_categories (id);
ALTER TABLE services ADD COLUMN IF NOT EXISTS duration_minutes INT NOT NULL DEFAULT 60;
ALTER TABLE services ADD COLUMN IF NOT EXISTS surge_eligible BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS service_bundles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL,
    description      TEXT NOT NULL DEFAULT '',
    service_ids      VARCHAR(255) NOT NULL,
    discount_percent INT NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS promo_campaigns (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(64) NOT NULL UNIQUE,
    discount_type VARCHAR(16) NOT NULL DEFAULT 'NOMINAL',
    discount_value BIGINT NOT NULL DEFAULT 0,
    min_total     BIGINT NOT NULL DEFAULT 0,
    max_discount  BIGINT NOT NULL DEFAULT 0,
    quota         INT NOT NULL DEFAULT 0,
    used          INT NOT NULL DEFAULT 0,
    starts_at     TIMESTAMP WITH TIME ZONE,
    ends_at       TIMESTAMP WITH TIME ZONE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS vouchers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL UNIQUE,
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    amount      BIGINT NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    expires_at  TIMESTAMP WITH TIME ZONE,
    used_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vouchers_consumer ON vouchers (consumer_id, status);

CREATE TABLE IF NOT EXISTS referrals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(32) NOT NULL UNIQUE,
    consumer_id    BIGINT NOT NULL REFERENCES users (id),
    invited_user_id BIGINT REFERENCES users (id),
    points         INT NOT NULL DEFAULT 0,
    status         VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_referrals_consumer ON referrals (consumer_id, status);

CREATE TABLE IF NOT EXISTS installment_plans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id),
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    months      INT NOT NULL CHECK (months IN (3, 6)),
    total       BIGINT NOT NULL,
    monthly     BIGINT NOT NULL,
    paid_months INT NOT NULL DEFAULT 0,
    status      VARCHAR(16) NOT NULL DEFAULT 'AKTIF',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS membership_tiers (
    code               VARCHAR(16) PRIMARY KEY,
    min_lifetime_points INT NOT NULL DEFAULT 0,
    discount_percent   INT NOT NULL DEFAULT 0,
    priority_weight    INT NOT NULL DEFAULT 0,
    free_visit         BOOLEAN NOT NULL DEFAULT FALSE,
    benefits           VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS wallet_settings (
    user_id             BIGINT PRIMARY KEY REFERENCES users (id),
    auto_topup_enabled  BOOLEAN NOT NULL DEFAULT FALSE,
    auto_topup_amount   BIGINT NOT NULL DEFAULT 100000,
    auto_topup_threshold BIGINT NOT NULL DEFAULT 50000,
    daily_limit         BIGINT NOT NULL DEFAULT 500000,
    cashback_percent    INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS review_votes (
    review_order_id BIGINT NOT NULL REFERENCES ratings (order_id),
    user_id         BIGINT NOT NULL REFERENCES users (id),
    helpful         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (review_order_id, user_id)
);

CREATE TABLE IF NOT EXISTS technician_replies (
    review_order_id BIGINT PRIMARY KEY REFERENCES ratings (order_id),
    reply           TEXT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS signatures (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    signer_id  BIGINT NOT NULL REFERENCES users (id),
    role       VARCHAR(16) NOT NULL,
    data_url   VARCHAR(512) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_signature UNIQUE (order_id, role)
);

CREATE TABLE IF NOT EXISTS checklist_templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services (id),
    title      VARCHAR(120) NOT NULL,
    step_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS checklist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    template_id BIGINT NOT NULL REFERENCES checklist_templates (id),
    done       BOOLEAN NOT NULL DEFAULT FALSE,
    photo_url  VARCHAR(512) NOT NULL DEFAULT '',
    note       VARCHAR(255) NOT NULL DEFAULT '',
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_checklist_item UNIQUE (order_id, template_id)
);

CREATE TABLE IF NOT EXISTS refund_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id),
    consumer_id BIGINT NOT NULL REFERENCES users (id),
    amount      BIGINT NOT NULL,
    reason      TEXT NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    note        VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS user_preferences (
    user_id          BIGINT PRIMARY KEY REFERENCES users (id),
    theme            VARCHAR(16) NOT NULL DEFAULT 'SISTEM',
    language         VARCHAR(8) NOT NULL DEFAULT 'ID',
    font_scale       INT NOT NULL DEFAULT 100,
    reduced_motion   BOOLEAN NOT NULL DEFAULT FALSE,
    quiet_start      VARCHAR(5) NOT NULL DEFAULT '',
    quiet_end        VARCHAR(5) NOT NULL DEFAULT '',
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS offline_queue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    path       VARCHAR(255) NOT NULL,
    payload    TEXT NOT NULL DEFAULT '',
    status     VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
