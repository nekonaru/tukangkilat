-- V9: review photos, chat read receipts, auto-online schedule and message moderation.
ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS read_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS review_photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    photo_url  VARCHAR(512) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_review_photo UNIQUE (order_id, photo_url)
);
CREATE INDEX IF NOT EXISTS idx_review_photos_order ON review_photos (order_id);

CREATE TABLE IF NOT EXISTS auto_online_schedules (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technician_id BIGINT NOT NULL REFERENCES users (id),
    day_of_week   INT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time    VARCHAR(5) NOT NULL,
    end_time      VARCHAR(5) NOT NULL,
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_auto_online UNIQUE (technician_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS message_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  BIGINT NOT NULL REFERENCES direct_messages (id),
    reporter_id BIGINT NOT NULL REFERENCES users (id),
    reason      VARCHAR(255) NOT NULL DEFAULT '',
    status      VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    resolved_by BIGINT REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_message_report UNIQUE (message_id, reporter_id)
);
CREATE INDEX IF NOT EXISTS idx_message_reports_status ON message_reports (status, created_at);
