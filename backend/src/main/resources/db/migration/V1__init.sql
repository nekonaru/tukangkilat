-- Tukang Kilat schema, PRD section 9. PostgreSQL dialect.

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              VARCHAR(64)  NOT NULL UNIQUE,
    password_hash         VARCHAR(255) NOT NULL,
    role                  VARCHAR(16)  NOT NULL CHECK (role IN ('KONSUMEN', 'TUKANG', 'ADMIN')),
    full_name             VARCHAR(120) NOT NULL,
    phone                 VARCHAR(32)  NOT NULL,
    status                VARCHAR(24)  NOT NULL DEFAULT 'AKTIF',
    failed_login_attempts INT          NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP WITH TIME ZONE,
    password_changed_at   TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now()
);

CREATE TABLE technician_profiles (
    user_id             BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    skills              TEXT         NOT NULL DEFAULT '',
    ktp_photo           VARCHAR(512),
    selfie_photo        VARCHAR(512),
    photo_url           VARCHAR(512),
    verification_status VARCHAR(32)  NOT NULL DEFAULT 'MENUNGGU_VERIFIKASI',
    rejection_reason    VARCHAR(255),
    is_online           BOOLEAN      NOT NULL DEFAULT FALSE,
    last_lat            DOUBLE PRECISION,
    last_lng            DOUBLE PRECISION,
    last_location_at    TIMESTAMP WITH TIME ZONE,
    rating_avg          DOUBLE PRECISION NOT NULL DEFAULT 0,
    jobs_count          INT          NOT NULL DEFAULT 0,
    service_radius_km   INT          NOT NULL DEFAULT 10
);

CREATE TABLE addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label        VARCHAR(64)  NOT NULL,
    full_address TEXT         NOT NULL,
    lat          DOUBLE PRECISION NOT NULL,
    lng          DOUBLE PRECISION NOT NULL,
    is_primary   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE services (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    icon       VARCHAR(64)  NOT NULL DEFAULT 'bolt',
    skill      VARCHAR(32)  NOT NULL DEFAULT 'LISTRIK',
    base_price BIGINT       NOT NULL CHECK (base_price >= 0),
    visit_fee  BIGINT       NOT NULL DEFAULT 25000 CHECK (visit_fee >= 0),
    is_active  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE time_slots (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label    VARCHAR(32) NOT NULL UNIQUE,
    capacity INT         NOT NULL DEFAULT 10 CHECK (capacity > 0)
);

CREATE TABLE promo_codes (
    code        VARCHAR(32) PRIMARY KEY,
    promo_type  VARCHAR(16)  NOT NULL CHECK (promo_type IN ('PERSEN', 'NOMINAL')),
    promo_value BIGINT       NOT NULL CHECK (promo_value > 0),
    valid_until TIMESTAMP WITH TIME ZONE  NOT NULL,
    quota       INT          NOT NULL DEFAULT 0
);

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(32)  NOT NULL UNIQUE,
    consumer_id    BIGINT       NOT NULL REFERENCES users (id),
    technician_id  BIGINT       REFERENCES users (id),
    service_id     BIGINT       NOT NULL REFERENCES services (id),
    description    TEXT         NOT NULL,
    address_id     BIGINT       NOT NULL REFERENCES addresses (id),
    scheduled_date DATE         NOT NULL,
    slot_id        BIGINT       NOT NULL REFERENCES time_slots (id),
    status         VARCHAR(32)  NOT NULL DEFAULT 'MENUNGGU_PEMBAYARAN',
    service_fee    BIGINT       NOT NULL,
    visit_fee      BIGINT       NOT NULL,
    discount       BIGINT       NOT NULL DEFAULT 0,
    total          BIGINT       NOT NULL,
    payment_method VARCHAR(24),
    payment_status VARCHAR(24)  NOT NULL DEFAULT 'MENUNGGU',
    finish_note    TEXT,
    created_at     TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now()
);

CREATE TABLE photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   VARCHAR(64)  NOT NULL UNIQUE,
    uploader_id BIGINT       NOT NULL REFERENCES users (id),
    filename    VARCHAR(255) NOT NULL,
    mime        VARCHAR(64)  NOT NULL,
    size_bytes  INT          NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now()
);

CREATE TABLE order_photos (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    photo_id BIGINT      NOT NULL REFERENCES photos (id),
    kind     VARCHAR(16) NOT NULL CHECK (kind IN ('MASALAH', 'BUKTI', 'LAPORAN'))
);

CREATE TABLE order_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status     VARCHAR(32) NOT NULL,
    actor_id   BIGINT      REFERENCES users (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE job_offers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    technician_id BIGINT      NOT NULL REFERENCES users (id),
    status        VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU'
                              CHECK (status IN ('MENUNGGU', 'DITERIMA', 'DITOLAK', 'KEDALUWARSA')),
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    reject_reason VARCHAR(255),
    is_revisit    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method       VARCHAR(24) NOT NULL,
    amount       BIGINT      NOT NULL CHECK (amount >= 0),
    reference_no VARCHAR(64),
    status       VARCHAR(24) NOT NULL DEFAULT 'MENUNGGU',
    paid_at      TIMESTAMP WITH TIME ZONE,
    expires_at   TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE ratings (
    order_id   BIGINT PRIMARY KEY REFERENCES orders (id) ON DELETE CASCADE,
    stars      INT         NOT NULL CHECK (stars BETWEEN 1 AND 5),
    tags       TEXT        NOT NULL DEFAULT '',
    comment    TEXT        NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE issue_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    reason      VARCHAR(32) NOT NULL,
    description TEXT        NOT NULL,
    status      VARCHAR(24) NOT NULL DEFAULT 'TERBUKA',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    sender_id  BIGINT      NOT NULL REFERENCES users (id),
    body       TEXT        NOT NULL CHECK (char_length(body) <= 2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE  NOT NULL,
    revoked    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now()
);

CREATE INDEX idx_orders_consumer      ON orders (consumer_id);
CREATE INDEX idx_orders_technician    ON orders (technician_id);
CREATE INDEX idx_orders_status        ON orders (status);
CREATE INDEX idx_orders_date_slot     ON orders (scheduled_date, slot_id);
CREATE INDEX idx_order_events_order   ON order_events (order_id);
CREATE INDEX idx_job_offers_order     ON job_offers (order_id);
CREATE INDEX idx_job_offers_tech      ON job_offers (technician_id);
CREATE INDEX idx_job_offers_status    ON job_offers (status);
CREATE INDEX idx_payments_order       ON payments (order_id);
CREATE INDEX idx_messages_order       ON messages (order_id);
CREATE INDEX idx_addresses_user       ON addresses (user_id);
CREATE INDEX idx_tech_online          ON technician_profiles (is_online);
CREATE INDEX idx_issue_reports_status ON issue_reports (status);
CREATE INDEX idx_refresh_tokens_user  ON refresh_tokens (user_id);
CREATE INDEX idx_order_photos_order   ON order_photos (order_id);
