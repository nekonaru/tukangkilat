-- Admin control center tables.
CREATE TABLE IF NOT EXISTS disputes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT NOT NULL REFERENCES issue_reports (id),
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    amount     BIGINT NOT NULL DEFAULT 0,
    decision   VARCHAR(16) NOT NULL DEFAULT 'MENUNGGU',
    admin_id   BIGINT REFERENCES users (id),
    note       TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT NOT NULL REFERENCES users (id),
    action     VARCHAR(64) NOT NULL,
    target     VARCHAR(64) NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_admin ON audit_logs (admin_id, created_at);
CREATE TABLE IF NOT EXISTS announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT NOT NULL REFERENCES users (id),
    title      VARCHAR(120) NOT NULL,
    body       TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS system_config (
    config_key   VARCHAR(64) PRIMARY KEY,
    config_value VARCHAR(255) NOT NULL
);
